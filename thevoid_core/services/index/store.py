"""A shared index on disk (round 65; design section 7).

    MyLab-index/
      INDEX.json               name, formats, licence policy
      .gitignore               build/
      entries/ab/ab3f...json   one immutable entry per file (entries.py)
      structures/9c/9c1e...cif redistributable structures only, named by
                               their SHA-256 and stored as given, so the
                               Batch Results window can check and open
                               them
      matches/4e/4e07...json   structure-match decisions, one per pair of
                               files; made where both files were at hand,
                               so a member without a CSD-derived file
                               still builds the same ids
      withdrawn/ab3f...json    a tombstone: entry_id, who, when, why
      build/                   generated by build(); never committed

Every write adds a new file named by its content, or by the pair it
decides, so two members adding to copies of the index merge with no
conflict (design Appendix A). build() is deterministic from the files
above.
"""

from __future__ import annotations

import datetime
import gzip
import hashlib
import json
import shutil
from dataclasses import dataclass, field
from pathlib import Path

from thevoid_core.services.index.entries import (
    ENTRY_FORMAT_VERSION,
    analysis_id,
    canonical,
    compute_entry_id,
    entry_to_report,
    make_entry,
)

INDEX_FILE = "INDEX.json"
INDEX_FORMAT = "the-void-index"

#: Summary columns compared between replicates (design section 6):
#: (column, absolute tolerance, relative tolerance) for replicates that
#: are the same determination in different files. Replicates from the
#: same file and method must agree to rounding (1e-9).
REPLICATE_TOLERANCES = (
    ("lcd_A", 0.15, 0.0),
    ("pld_A", 0.15, 0.0),
    ("void_fraction_percent", 0.0, 0.05),
    ("channel_asa_m2_per_g", 0.0, 0.05),
    ("density_g_cm3", 0.0, 0.005),
)

INDEX_COLUMNS = ["name", "entry_id", "framework_key", "structure_id", "determination_id",
                 "method_key", "the_void_version", "contributor", "added", "origin",
                 "licence", "structure_stored", "aliases", "also_added_by"]


def _fanned(folder: Path, name: str, suffix: str) -> Path:
    return folder / name[:2] / f"{name}{suffix}"


def _write_new(path: Path, text: str) -> bool:
    """Write a file that must not exist yet; False if it already does
    (with the same content, being named by it)."""
    if path.exists():
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".part")
    temporary.write_text(text, encoding="utf-8")
    temporary.replace(path)
    return True


def pair_name(a: str, b: str) -> str:
    low, high = sorted((a, b))
    return hashlib.sha256(f"{low}|{high}".encode()).hexdigest()


@dataclass
class AddResult:
    added: list = field(default_factory=list)        # entry ids
    present: list = field(default_factory=list)      # entry ids already in the index
    skipped: list = field(default_factory=list)      # (file, reason)
    stored: list = field(default_factory=list)       # file names whose CIF was stored
    withheld: list = field(default_factory=list)     # (file, licence basis)
    decisions: int = 0


@dataclass
class RefreshResult:
    #: (old entry id, new entry id) for each entry analysed again.
    refreshed: list = field(default_factory=list)
    #: (old entry id, file name, reason) for each stale entry left as it is.
    skipped: list = field(default_factory=list)
    #: The stale, current entries found (before --limit).
    planned: int = 0
    #: With dry_run: the entry ids that would be analysed again.
    would_refresh: list = field(default_factory=list)


@dataclass
class BuildResult:
    folder: Path
    rows: int = 0
    structures: int = 0
    determinations: int = 0
    fits: int = 0
    undecided: list = field(default_factory=list)
    problems: list = field(default_factory=list)


class IndexProblem(Exception):
    """Not an index, or one this version cannot read."""


class Index:
    """A shared index folder."""

    def __init__(self, path, info: dict):
        self.path = Path(path)
        self.info = info
        self._keys = None  # framework_key -> {file SHA-256}, built on first add
        self._analyses = None  # analysis_id -> entry_id, built on first add
        self._known = None  # recorded match decisions, read on first add

    # -- creating and opening ------------------------------------------

    @classmethod
    def init(cls, path, *, name: str, results_licence: str = "CC-BY-4.0",
             maintainers=(), standard_config: dict | None = None) -> "Index":
        from thevoid_core.services.index.identity import KEY_VERSION, LOOSE, TIGHT
        from thevoid_core.version import __version__

        path = Path(path)
        if (path / INDEX_FILE).exists():
            raise IndexProblem(f"{path} is already an index")
        path.mkdir(parents=True, exist_ok=True)
        info = {
            "format": INDEX_FORMAT,
            "name": name,
            "created": datetime.date.today().isoformat(),
            "created_with": __version__,
            "entry_format_version": ENTRY_FORMAT_VERSION,
            "key_version": KEY_VERSION,
            "match_tolerances": {"structure": LOOSE, "determination": TIGHT},
            "results_licence": results_licence,
            "structure_policy": "stored only with a recorded basis for redistribution "
                                "(services/index/licence.py); otherwise results and "
                                "aliases only",
            "maintainers": list(maintainers),
            "standard_config": standard_config or {},
        }
        (path / INDEX_FILE).write_text(json.dumps(info, indent=1), encoding="utf-8")
        (path / ".gitignore").write_text("build/\n*.part\n", encoding="utf-8")
        for folder in ("entries", "structures", "matches", "withdrawn"):
            (path / folder).mkdir(exist_ok=True)
        return cls(path, info)

    @classmethod
    def open(cls, path) -> "Index":
        path = Path(path)
        try:
            info = json.loads((path / INDEX_FILE).read_text(encoding="utf-8"))
        except FileNotFoundError:
            raise IndexProblem(f"{path} is not an index (no {INDEX_FILE}; "
                              "the-void-index init makes one)") from None
        if info.get("format") != INDEX_FORMAT:
            raise IndexProblem(f"{path / INDEX_FILE} is not a the-void-index file")
        if info.get("entry_format_version", 0) > ENTRY_FORMAT_VERSION:
            raise IndexProblem(f"{path} uses entry format {info['entry_format_version']}; "
                              f"this version of the Void reads up to {ENTRY_FORMAT_VERSION}")
        return cls(path, info)

    # -- reading -------------------------------------------------------

    def entry_files(self):
        return sorted((self.path / "entries").glob("*/*.json"))

    def load_entries(self, problems: list | None = None) -> dict:
        """{entry_id: entry}. An entry whose content no longer matches its
        name is reported in problems and left out."""
        out = {}
        for file in self.entry_files():
            try:
                entry = json.loads(file.read_text(encoding="utf-8"))
            except (OSError, ValueError) as exc:
                if problems is not None:
                    problems.append(f"{file.relative_to(self.path)}: unreadable ({exc})")
                continue
            name = file.stem
            if entry.get("entry_id") != name or compute_entry_id(entry) != name:
                if problems is not None:
                    problems.append(f"{file.relative_to(self.path)}: content does not match "
                                    "its id (edited by hand?)")
                continue
            if entry.get("entry_format_version", 0) > ENTRY_FORMAT_VERSION:
                if problems is not None:
                    problems.append(f"{name[:12]}: entry format "
                                    f"{entry['entry_format_version']} is newer than this version")
                continue
            out[name] = entry
        return out

    def withdrawn(self) -> dict:
        out = {}
        for file in sorted((self.path / "withdrawn").glob("*.json")):
            try:
                out[file.stem] = json.loads(file.read_text(encoding="utf-8"))
            except (OSError, ValueError):
                continue
        return out

    def current_entries(self, problems: list | None = None) -> dict:
        withdrawn = self.withdrawn()
        return {k: v for k, v in self.load_entries(problems).items() if k not in withdrawn}

    def stored_structure(self, sha: str) -> Path | None:
        path = _fanned(self.path / "structures", sha, ".cif")
        return path if path.is_file() else None

    def decisions(self) -> dict:
        """The recorded match decisions, in MatchCache's form."""
        out = {}
        for file in sorted((self.path / "matches").glob("*/*.json")):
            try:
                record = json.loads(file.read_text(encoding="utf-8"))
                low, high = sorted(record["files"])
            except (OSError, ValueError, KeyError, TypeError):
                continue
            if record.get("same_structure") is not None:
                out[f"structure:{low}:{high}"] = bool(record["same_structure"])
            if record.get("same_determination") is not None:
                out[f"determination:{low}:{high}"] = bool(record["same_determination"])
        return out

    # -- adding --------------------------------------------------------

    def _loader(self, sha: str, local: dict):
        def load():
            from pymatgen.core import Structure

            path = local.get(sha) or self.stored_structure(sha) or self._look_nearby(sha)
            return Structure.from_file(path) if path else None
        return load

    def _look_nearby(self, sha: str):
        """A structure file not stored in the index, looked for (by
        SHA-256) in the folders an add is working from: its --structures
        folders and the folders of the files it is adding, which often
        hold the relatives it has to be compared with. Hashed once per
        set of folders."""
        folders = tuple(sorted(str(f) for f in getattr(self, "_nearby_folders", ())))
        if not folders:
            return None
        if getattr(self, "_nearby_key", None) != folders:
            self._nearby = _hash_folders(folders)
            self._nearby_key = folders
        return self._nearby.get(sha)

    def _record_decisions(self, sha: str, key: str, others: dict, local: dict) -> int:
        """Decide, and record, whether the file `sha` is the same
        structure and determination as each other file of its key; only
        pairs with both files at hand, and not decided already."""
        from thevoid_core.services.index.identity import MatchCache, Member

        if getattr(self, "_known", None) is None:
            self._known = self.decisions()
        known = self._known
        cache = MatchCache(known)
        me = Member(sha, sha, key, self._loader(sha, local))
        written = 0
        for other in sorted(others):
            if other == sha:
                continue
            low, high = sorted((sha, other))
            if f"structure:{low}:{high}" in known:
                continue
            them = Member(other, other, key, self._loader(other, local))
            same = cache.decide("structure", me, them)
            if f"structure:{low}:{high}" not in cache.new:
                continue  # a structure was missing: undecided
            determination = cache.decide("determination", me, them) if same else False
            record = {"files": [low, high], "same_structure": same,
                      "same_determination": determination,
                      "identity_version": self.info.get("key_version", 1),
                      "tolerances": self.info.get("match_tolerances")}
            if _write_new(_fanned(self.path / "matches", pair_name(low, high), ".json"),
                          json.dumps(record, indent=1)):
                written += 1
            known[f"structure:{low}:{high}"] = same
            known[f"determination:{low}:{high}"] = determination
        return written

    def add_entry(self, entry: dict, structure_path=None, *, local: dict | None = None,
                  result: AddResult | None = None) -> str:
        """Add one entry (and its structure, if redistributable).
        "added" or "present"."""
        result = result if result is not None else AddResult()
        entry_id = entry["entry_id"]
        if self._analyses is None:
            self._analyses = {analysis_id(e): k for k, e in self.load_entries().items()}
        same = self._analyses.get(analysis_id(entry))
        if same is not None:
            # The same analysis of the same file, already in: however it
            # was annotated this time, nothing new to record.
            result.present.append(same)
            return "present"
        text = json.dumps(entry, indent=1, sort_keys=True, ensure_ascii=False)
        status = "added" if _write_new(_fanned(self.path / "entries", entry_id, ".json"),
                                       text) else "present"
        (result.added if status == "added" else result.present).append(entry_id)
        self._analyses[analysis_id(entry)] = entry_id
        if status == "present":
            return status
        s = entry["structure"]
        if structure_path is not None and s["licence"]["redistributable"]:
            target = _fanned(self.path / "structures", s["file_sha256"], ".cif")
            if not target.exists():
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(structure_path, target)
            result.stored.append(s["file_name"])
        elif not s["licence"]["redistributable"]:
            result.withheld.append((s["file_name"], s["licence"]["basis"]))
        local = dict(local or {})
        if structure_path is not None:
            local[s["file_sha256"]] = Path(structure_path)
        if self._keys is None:
            self._keys = {}
            for e in self.load_entries().values():
                self._keys.setdefault(e["structure"]["framework_key"], set()).add(
                    e["structure"]["file_sha256"])
        same_key = self._keys.setdefault(s["framework_key"], set())
        result.decisions += self._record_decisions(s["file_sha256"], s["framework_key"],
                                                   same_key, local)
        same_key.add(s["file_sha256"])
        return status

    def add_report(self, report: dict, structure_path, *, contributor: str, note: str = "",
                   origin: str | None = None, declared_licence: dict | None = None,
                   search_dirs=()) -> AddResult:
        """One report and the file it was computed from (the main window's
        File > Shared Index > Add Current Structure...). Raises ValueError
        if the file has changed since, or the report has no results."""
        if not report.get("results"):
            raise ValueError("the report has no results: run an analysis first")
        out = AddResult()
        path = Path(structure_path)
        entry = make_entry(report, path, contributor=contributor, note=note, origin=origin,
                           declared_licence=declared_licence)
        self._nearby_folders = {Path(d) for d in search_dirs} | {path.parent}
        try:
            self.add_entry(entry, path, local={entry["structure"]["file_sha256"]: path},
                           result=out)
        finally:
            self._nearby_folders = set()
        return out

    def add_results(self, results_folder, *, contributor: str, note: str = "",
                    origin: str | None = None, declared_licence: dict | None = None,
                    search_dirs=(), progress=None, only=None) -> AddResult:
        """Every report in a the-void-analyze results folder (or, with
        only, the rows whose file is in it). Each report's structure file
        is found as the Batch Results window finds it, and must match the
        report's SHA-256."""
        from thevoid_core.services.batch_results import (
            load_batch_results,
            locate_structure,
            read_report,
        )

        results = load_batch_results(results_folder)
        out = AddResult()
        local = {}
        self._nearby_folders = set(Path(d) for d in search_dirs)
        rows = [r for r in results.rows if only is None or r.get("file") in only]
        for number, row in enumerate(rows, start=1):
            name = row.get("file") or f"row {number}"
            if progress is not None:
                progress(name, number, len(rows))
            report = read_report(row)
            if not report:
                out.skipped.append((name, "no JSON report beside the summary"))
                continue
            located = locate_structure(row, results, extra_dirs=search_dirs)
            if located.status != "verified":
                reason = {"mismatch": "the structure file has changed since it was analysed",
                          "unverified": "the report records no SHA-256",
                          "missing": "structure file not found"}.get(located.status,
                                                                     located.status)
                out.skipped.append((name, reason))
                continue
            joined = {k: v for k, v in row.values.items()
                      if k.startswith(("ref_", "fn_")) and v not in (None, "")}
            try:
                entry = make_entry(report, located.path, contributor=contributor, note=note,
                                   origin=origin, declared_licence=declared_licence,
                                   joined=joined)
            except Exception as exc:
                out.skipped.append((name, f"{type(exc).__name__}: {exc}"))
                continue
            local[entry["structure"]["file_sha256"]] = located.path
            self._nearby_folders.add(Path(located.path).parent)
            self.add_entry(entry, located.path, local=local, result=out)
        self._nearby_folders = set()
        return out

    def withdraw(self, entry_id: str, *, reason: str, by: str) -> Path:
        entries = self.load_entries()
        matches = [k for k in entries if k.startswith(entry_id)]
        if len(matches) != 1:
            raise IndexProblem(f"{entry_id!r} matches {len(matches)} entries")
        path = self.path / "withdrawn" / f"{matches[0]}.json"
        _write_new(path, json.dumps({"entry_id": matches[0], "by": by, "reason": reason,
                                     "date": datetime.date.today().isoformat()}, indent=1))
        return path

    # -- identity over the whole index ---------------------------------

    def placements(self, entries: dict, search_dirs=(), save_decisions=True):
        """(placements by entry id, MatchCache) for these entries."""
        from thevoid_core.services.index.identity import MatchCache, Member, assign_ids

        local = _hash_folders(search_dirs) if search_dirs else {}
        cache = MatchCache(self.decisions())
        members = [Member(k, e["structure"]["file_sha256"], e["structure"]["framework_key"],
                          self._loader(e["structure"]["file_sha256"], local))
                   for k, e in sorted(entries.items())]
        placed = {p.id: p for p in assign_ids(members, cache)}
        if save_decisions and cache.new:
            by_pair = {}
            for key, same in cache.new.items():
                level, low, high = key.split(":")
                by_pair.setdefault((low, high), {})[level] = same
            known = self.decisions()
            for (low, high), levels in by_pair.items():
                structure = levels.get("structure", known.get(f"structure:{low}:{high}"))
                determination = levels.get("determination",
                                           known.get(f"determination:{low}:{high}"))
                if structure is False:
                    determination = False
                target = _fanned(self.path / "matches", pair_name(low, high), ".json")
                if target.exists():
                    continue
                _write_new(target, json.dumps({
                    "files": [low, high], "same_structure": structure,
                    "same_determination": determination,
                    "identity_version": self.info.get("key_version", 1),
                    "tolerances": self.info.get("match_tolerances")}, indent=1))
        return placed, cache

    # -- building ------------------------------------------------------

    def build(self, *, search_dirs=()) -> BuildResult:
        """build/: summary.csv and a report per entry (a results folder the
        Batch Results window opens), index.json.gz (the CoRE-style table)
        and BUILD.json (what the build found)."""
        from thevoid_core.services.report import SUMMARY_COLUMNS, summary_csv

        from thevoid_core.services.index.staleness import assess

        problems = []
        entries, also = _one_per_analysis(self.current_entries(problems))
        placed, cache = self.placements(entries, search_dirs)
        staleness = assess(entries)
        folder = self.path / "build"
        if folder.exists():
            shutil.rmtree(folder)
        folder.mkdir()
        rows = []
        for entry_id, entry in sorted(entries.items(),
                                      key=lambda kv: (kv[1]["structure"]["file_name"], kv[0])):
            s, a = entry["structure"], entry["analysis"]
            stem = Path(s["file_name"]).stem
            row_file = f"{stem}~{entry_id[:10]}.cif"
            stored = self.stored_structure(s["file_sha256"])
            input_file = (stored.relative_to(self.path).as_posix() if stored else s["file_name"])
            report = entry_to_report(entry, input_file)
            (folder / f"{stem}~{entry_id[:10]}.json").write_text(
                json.dumps(report, indent=1), encoding="utf-8")
            p = placed[entry_id]
            row = dict(a["summary"])
            row["file"] = row_file
            row.update(a.get("joined") or {})
            row.update({
                "name": s["file_name"], "entry_id": entry_id, "framework_key": p.key,
                "structure_id": p.structure_id, "determination_id": p.determination_id,
                "method_key": a["method_key"],
                "the_void_version": a["software"].get("the_void", ""),
                "contributor": entry["contributor"]["name"],
                "added": entry["contributor"]["added"], "origin": s["origin"],
                "licence": s["licence"]["spdx"] or s["licence"]["basis"],
                "structure_stored": "yes" if stored else "no",
                "aliases": "; ".join(f"{x['kind']}:{x['value']}" for x in s["aliases"]),
                "also_added_by": "; ".join(f"{e['contributor']['name']} "
                                           f"{e['contributor']['added']}"
                                           for e in also.get(entry_id, [])),
                # Round 67: out of date, and by what (staleness.py).
                "stale_columns": ", ".join(sorted(staleness[entry_id].columns)),
                "superseded_by": staleness[entry_id].superseded_by or "",
            })
            rows.append(row)
        (folder / "summary.csv").write_text(summary_csv(rows), encoding="utf-8")
        columns = list(SUMMARY_COLUMNS)
        for row in rows:
            columns += [k for k in row if k not in columns]
        table = {"source": {"name": self.info.get("name"), "format": INDEX_FORMAT,
                            "entries": len(rows),
                            "built": datetime.date.today().isoformat()},
                 "columns": columns,
                 "rows": [[row.get(c) for c in columns] for row in rows]}
        with gzip.open(folder / "index.json.gz", "wt", encoding="utf-8") as handle:
            json.dump(table, handle)
        result = BuildResult(folder, len(rows),
                             len({p.structure_id for p in placed.values()}),
                             len({p.determination_id for p in placed.values()}),
                             cache.fits, sorted(cache.undecided), problems)
        (folder / "BUILD.json").write_text(json.dumps({
            "entries": result.rows, "structures": result.structures,
            "determinations": result.determinations, "fits": result.fits,
            "undecided_pairs": result.undecided, "problems": problems,
            "withdrawn": len(self.withdrawn())}, indent=1), encoding="utf-8")
        return result

    # -- staleness (round 67) -------------------------------------------

    def stale(self) -> list:
        """[(entry, Staleness)] for current entries (not superseded by a
        newer analysis of the same file with the same options) whose
        numbers a later version of the Void computes differently."""
        from thevoid_core.services.index.staleness import assess

        entries, _also = _one_per_analysis(self.current_entries())
        verdicts = assess(entries)
        return [(entries[k], v) for k, v in sorted(verdicts.items())
                if v.stale and v.superseded_by is None]

    def refresh(self, *, contributor: str, search_dirs=(), limit: int | None = None,
                dry_run: bool = False, progress=None, jobs: int = 1) -> RefreshResult:
        """Analyse stale entries again with this version and the same
        options, and add the new entries (nothing is overwritten: the old
        entry stays, superseded). Needs each structure file: stored in the
        index, or found under search_dirs by its SHA-256. An entry from
        the Analysis menu, whose options were inferred from its results,
        cannot be rerun exactly and is skipped.

        jobs > 1 (round 68) analyses that many structures at once, in
        separate processes; the new entries are then added one at a time,
        in the order of the stale list, so the index is written exactly
        as a one-job refresh writes it."""
        from concurrent.futures import ProcessPoolExecutor

        from thevoid_core.services.report import AnalysisConfig, file_sha256
        from thevoid_core.version import __version__

        if jobs < 1:
            raise ValueError("jobs must be at least 1")
        stale = self.stale()
        out = RefreshResult(planned=len(stale))
        local = _hash_folders(search_dirs) if search_dirs else {}
        fields = set(AnalysisConfig.__dataclass_fields__)
        plan = []
        for entry, verdict in stale:
            s, a = entry["structure"], entry["analysis"]
            if limit is not None and len(plan) >= limit:
                break
            config = dict(a.get("config") or {})
            if config.get("inferred_from_results"):
                out.skipped.append((entry["entry_id"], s["file_name"],
                                    "an Analysis-menu entry: its options cannot be rerun "
                                    "exactly; run it again in the application"))
                continue
            source = local.get(s["file_sha256"]) or self.stored_structure(s["file_sha256"])
            if source is None:
                out.skipped.append((entry["entry_id"], s["file_name"],
                                    "structure file not stored in the index; give its "
                                    "folder with --structures"))
                continue
            if file_sha256(source) != s["file_sha256"]:
                out.skipped.append((entry["entry_id"], s["file_name"],
                                    "the structure file has changed (its SHA-256 is not the "
                                    "entry's): run the-void-index verify"))
                continue
            dropped = sorted(set(config) - fields)
            note = (f"refresh of {entry['entry_id'][:12]} (the Void "
                    f"{a['software'].get('the_void', '?')} -> {__version__}; "
                    f"stale: {', '.join(sorted(verdict.columns))})")
            if dropped:
                note += f"; options no longer known: {', '.join(dropped)}"
            options = {k: v for k, v in config.items() if k in fields}
            plan.append((entry, str(source), options, note))
        if dry_run:
            out.would_refresh = [entry["entry_id"] for entry, *_ in plan]
            return out

        tasks = [(str(source), entry["structure"]["file_name"], options, contributor, note,
                  entry) for entry, source, options, note in plan]
        if jobs == 1 or len(tasks) <= 1:
            results = map(lambda t: _refresh_one(*t), tasks)
            pool = None
        else:
            pool = ProcessPoolExecutor(max_workers=jobs)
            results = pool.map(_refresh_one, *zip(*tasks))
        try:
            for number, ((entry, source, _options, _note), outcome) in enumerate(
                    zip(plan, results), start=1):
                s = entry["structure"]
                if progress is not None:
                    progress(s["file_name"], number, len(plan))
                if isinstance(outcome, str):
                    out.skipped.append((entry["entry_id"], s["file_name"], outcome))
                    continue
                stored = self.stored_structure(s["file_sha256"])
                self.add_entry(outcome, None if stored else source,
                               local={s["file_sha256"]: Path(source)}, result=AddResult())
                out.refreshed.append((entry["entry_id"], outcome["entry_id"]))
        finally:
            if pool is not None:
                pool.shutdown()
        return out

    # -- looking things up ---------------------------------------------

    def find(self, path, *, search_dirs=()) -> list:
        """[(relation, entry)] for a structure file, closest first:
        "same file", "same determination", "same structure", "same key,
        not compared" (a structure was not at hand) and "same key,
        different structure"."""
        from pymatgen.core import Structure

        from thevoid_core.services.index.identity import MatchCache, Member, framework_key
        from thevoid_core.services.report import file_sha256

        path = Path(path)
        sha = file_sha256(path)
        key = framework_key(Structure.from_file(path)).key
        local = _hash_folders(search_dirs) if search_dirs else {}
        local[sha] = path
        cache = MatchCache(self.decisions())
        me = Member("query", sha, key, self._loader(sha, local))
        order = ["same file", "same determination", "same structure",
                 "same key, not compared", "same key, different structure"]
        out = []
        for entry in self.current_entries().values():
            s = entry["structure"]
            if s["framework_key"] != key:
                continue
            if s["file_sha256"] == sha:
                relation = "same file"
            else:
                them = Member(s["file_sha256"], s["file_sha256"], key,
                              self._loader(s["file_sha256"], local))
                if cache.decide("structure", me, them):
                    relation = ("same determination"
                                if cache.decide("determination", me, them) else "same structure")
                elif cache.undecided:
                    relation = "same key, not compared"
                    cache.undecided.clear()
                else:
                    relation = "same key, different structure"
            out.append((relation, entry))
        return sorted(out, key=lambda x: (order.index(x[0]), x[1]["entry_id"]))

    # -- checking ------------------------------------------------------

    def verify(self, *, search_dirs=()) -> list:
        """Everything wrong with the index, as messages; [] if nothing:

        - entries edited by hand (content no longer matches the id), or
          in a newer format;
        - stored structures whose SHA-256 is not their name;
        - tombstones for entries that do not exist;
        - replicates that disagree: the same determination and method,
          compared to rounding when from the same file, and within
          REPLICATE_TOLERANCES otherwise; every disagreeing pair is
          reported.
        """
        from thevoid_core.services.report import file_sha256

        problems = []
        entries = self.load_entries(problems)
        for file in sorted((self.path / "structures").glob("*/*.cif")):
            if file_sha256(file) != file.stem:
                problems.append(f"{file.relative_to(self.path)}: its SHA-256 is not its name")
        for entry_id in self.withdrawn():
            if entry_id not in entries:
                problems.append(f"withdrawn/{entry_id}.json: no such entry")
        current, _also = _one_per_analysis(
            {k: v for k, v in entries.items() if k not in self.withdrawn()})
        placed, _cache = self.placements(current, search_dirs, save_decisions=False)
        groups = {}
        for entry_id, entry in current.items():
            groups.setdefault((placed[entry_id].determination_id,
                               entry["analysis"]["method_key"]), []).append(entry)
        # Every pair, in id order: which entry comes first must not change
        # what is reported (round 66: comparing all with the first one made
        # a bad first entry report once per replicate, and a bad later one
        # only once).
        for (determination, _method), group in sorted(groups.items()):
            group = sorted(group, key=lambda e: e["entry_id"])
            for i, first in enumerate(group):
                for other in group[i + 1:]:
                    problems += _compare_replicates(first, other)
        return problems


def _refresh_one(source: str, file_name: str, options: dict, contributor: str, note: str,
                 previous: dict):
    """Worker (module level, so it pickles): analyse one structure file
    again and return the new entry, or a message if the analysis could
    not be run at all. The file is analysed under its original name, so
    its aliases and report read as before."""
    import logging
    import tempfile
    import warnings

    from pymatgen.core import Structure

    from thevoid_core.services.report import AnalysisConfig, run_analysis

    logging.disable(logging.WARNING)
    options = {k: (tuple(v) if k == "xrd_two_theta_range" else v) for k, v in options.items()}
    try:
        with warnings.catch_warnings(), tempfile.TemporaryDirectory(
                prefix="thevoid-refresh-") as folder:
            warnings.simplefilter("ignore", UserWarning)
            path = Path(folder) / file_name
            shutil.copyfile(source, path)
            report = run_analysis(Structure.from_file(path), AnalysisConfig(**options),
                                  source=str(path))
            return make_entry(report, path, contributor=contributor, note=note,
                              joined=previous["analysis"].get("joined"), previous=previous)
    except Exception as exc:  # a file that no longer reads, say
        return f"could not be analysed: {type(exc).__name__}: {exc}"
    finally:
        logging.disable(logging.NOTSET)


def _one_per_analysis(entries: dict):
    """(entries, {kept id: [the others]}): of entries that are the same
    analysis (analysis_id), the first added is kept (then the smaller
    id); the others are listed beside it."""
    by_analysis = {}
    for entry_id, entry in entries.items():
        by_analysis.setdefault(analysis_id(entry), []).append(entry)
    kept, also = {}, {}
    for group in by_analysis.values():
        group.sort(key=lambda e: (e["contributor"]["added"], e["entry_id"]))
        kept[group[0]["entry_id"]] = group[0]
        if len(group) > 1:
            also[group[0]["entry_id"]] = group[1:]
    return kept, also


def _compare_replicates(a: dict, b: dict) -> list:
    same_file = a["structure"]["file_sha256"] == b["structure"]["file_sha256"]
    out = []
    for column, absolute, relative in REPLICATE_TOLERANCES:
        x, y = a["analysis"]["summary"].get(column), b["analysis"]["summary"].get(column)
        if x is None or y is None:
            if (x is None) != (y is None):
                out.append(f"replicates {a['entry_id'][:10]} and {b['entry_id'][:10]}: "
                           f"{column} is {x} against {y}")
            continue
        x, y = float(x), float(y)
        limit = 1e-9 * max(abs(x), abs(y), 1.0) if same_file else max(
            absolute, relative * max(abs(x), abs(y)))
        if abs(x - y) > limit:
            out.append(f"replicates {a['entry_id'][:10]} and {b['entry_id'][:10]} "
                       f"({'same file' if same_file else 'same determination'}): {column} "
                       f"{x:g} against {y:g}")
    return out


def _hash_folders(folders) -> dict:
    """{SHA-256: path} for the CIFs under folders."""
    from thevoid_core.services.report import file_sha256

    out = {}
    for folder in folders:
        for path in sorted(Path(folder).rglob("*.cif")):
            digest = file_sha256(path)
            if digest:
                out.setdefault(digest, path)
    return out


